"""Agensi submission-package preparation.

No Agensi publishing API was found in public material, so this module only
*prepares* files for manual upload. It never contacts any network service and
never sets prices: pricing text is a proposal that needs owner approval.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from . import __version__, discover_skills, frontmatter
from .packager import build_agensi, sha256
from .validator import validate_skill

PRICING_PROPOSAL = {
    "free": "Free (adoption and feedback)",
    "paid": "Paid, one-time (owner to set amount)",
    "premium": "Premium, one-time or subscription (owner to set amount)",
}
HUMAN_GATES = [
    "Owner approves public release of version " + __version__,
    "Owner completes Agensi creator verification (done by owner, not automated)",
    "Owner accepts Agensi creator terms (not accepted by this tool)",
    "Owner sets final prices (tool only proposes tiers)",
    "Owner uploads packages via the Agensi dashboard and reviews its security-scan result",
]


def section(body: str, title: str, limit: int = 1500) -> str:
    m = re.search(rf"(?ims)^##\s+[^\n]*{re.escape(title)}[^\n]*\n(.*?)(?=^##\s|\Z)", body)
    return (m.group(1).strip()[:limit] if m else "").strip()


def listing(skill: Path) -> str:
    fm, body, _ = frontmatter.parse((skill / "SKILL.md").read_text(encoding="utf-8"))
    meta = fm["metadata"]
    title = meta.get("title") or skill.name.replace("-", " ").title()
    tier = meta.get("tier", "paid")
    desc = fm["description"]
    short = re.split(r"(?<=\.)\s", desc)[0][:160]
    return f"""# {title}

> Generated by `kw-skills marketplace prepare agensi`. Review before submitting. Nothing here has been published.

- **Skill id:** `{skill.name}`
- **Short description:** {short}
- **Category:** {meta['category']}
- **Tags:** {meta['tags']}
- **Version:** {meta['version']} (see CHANGELOG.md)
- **License:** {fm['license']}
- **Requirements:** {fm.get('compatibility', 'None beyond a SKILL.md-capable agent')}
- **Pricing recommendation (proposal, NOT approved):** {PRICING_PROPOSAL.get(tier, PRICING_PROPOSAL['paid'])}

## Detailed description

{desc}

{section(body, 'Purpose')}

## Installation

Via Agensi: connect your agent per Agensi's instructions (buyers consume skills through its MCP connector; no file download is described on the Agensi homepage).
Manual / open-source route: copy the `{skill.name}/` folder to `.claude/skills/` (Claude Code), `.github/skills/` (GitHub Copilot) or use the Cursor package. See INSTALLATION.md.

## Usage examples

{section(body, 'Examples')}

## Limitations

{section(body, 'Limitations')}
"""


def prepare(root: Path) -> dict:
    out = root / "marketplace" / "agensi"
    skills = discover_skills(root)
    errors = {s.name: [f.message for f in validate_skill(s) if f.severity == "error"] for s in skills}
    blocking = {k: v for k, v in errors.items() if v}
    if blocking:
        raise ValueError(f"validation errors block marketplace preparation: {sorted(blocking)}")
    (out / "listings").mkdir(parents=True, exist_ok=True)
    for s in skills:
        (out / "listings" / f"{s.name}.md").write_text(listing(s), encoding="utf-8")
    pk = out / "packages"
    pk.mkdir(parents=True, exist_ok=True)
    arts = build_agensi(skills, pk)
    sums = "".join(f"{sha256(a)}  {a.name}\n" for a in arts)
    (pk / "SHA256SUMS").write_text(sums, encoding="utf-8")
    return {"listings": len(skills), "packages": len(arts), "dir": str(out)}


def report(root: Path) -> dict:
    out = root / "marketplace" / "agensi"
    skills = discover_skills(root)
    rows = []
    for s in skills:
        errs = [f for f in validate_skill(s) if f.severity == "error"]
        rows.append({
            "skill": s.name,
            "structurally_valid": not errs,
            "listing": (out / "listings" / f"{s.name}.md").is_file(),
            "package": any((out / "packages").glob(f"{s.name}-*.zip")),
            "real_world_evaluation": (root / "evals" / "results" / f"{s.name}.json").is_file(),
        })
    ready = all(r["structurally_valid"] and r["listing"] and r["package"] for r in rows)
    return {
        "submission_assets_ready": ready,
        "evaluated_in_real_world": sum(r["real_world_evaluation"] for r in rows),
        "skills": rows,
        "pending_human_gates": HUMAN_GATES,
        "note": "Assets ready is not the same as approved or published. Nothing has been submitted.",
    }
