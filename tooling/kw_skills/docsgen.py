"""Documentation generator: skill catalogue kept in sync with the canonical skills."""
from __future__ import annotations

from pathlib import Path

from . import discover_skills, frontmatter

HEADER = "<!-- generated by `kw-skills docs`; do not edit by hand -->\n# Skill catalogue\n\n"


def catalogue(root: Path) -> str:
    rows = ["| Skill | Category | Version | Tier | Description |", "|---|---|---|---|---|"]
    for s in discover_skills(root):
        fm, _, _ = frontmatter.parse((s / "SKILL.md").read_text(encoding="utf-8"))
        m = fm.get("metadata", {})
        rel = s.relative_to(root).as_posix()
        short = fm["description"].split(". ")[0].rstrip(".") + "."
        rows.append(f"| [`{s.name}`]({'../' + rel}/SKILL.md) | {m.get('category','')} | {m.get('version','')} | {m.get('tier','paid')} | {short} |")
    return HEADER + "\n".join(rows) + "\n"


def write(root: Path) -> Path:
    p = root / "docs" / "SKILL_CATALOGUE.md"
    p.write_text(catalogue(root), encoding="utf-8")
    return p


def check(root: Path) -> bool:
    p = root / "docs" / "SKILL_CATALOGUE.md"
    return p.is_file() and p.read_text(encoding="utf-8") == catalogue(root)
