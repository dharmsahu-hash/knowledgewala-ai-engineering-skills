"""Platform adapters: one canonical source -> per-platform packages.

Every adapter is a pure function of the canonical skill directory. Zips are
deterministic (fixed timestamps, sorted entries) so checksums are reproducible.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import zipfile
from pathlib import Path

from . import __version__, discover_skills, frontmatter

PLATFORMS = ("generic", "claude-code", "cursor", "github-copilot", "agensi")
EXCLUDE_DIRS = {"tests", "__pycache__"}
ZIP_TIME = (2026, 1, 1, 0, 0, 0)
PRODUCT = "knowledgewala-ai-engineering-skills"
DESCRIPTION = "Structured, reusable AI engineering workflows (requirements to release) with human approval gates."


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def skill_files(skill: Path) -> list[Path]:
    out = []
    for p in sorted(skill.rglob("*")):
        rel = p.relative_to(skill)
        if p.is_file() and not (set(rel.parts) & EXCLUDE_DIRS) and p.suffix != ".pyc":
            out.append(p)
    return out


def copy_skill(skill: Path, dest: Path) -> None:
    for p in skill_files(skill):
        t = dest / p.relative_to(skill)
        t.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(p, t)


def zip_dir(src: Path, zip_path: Path, arcroot: str | None = None) -> Path:
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(x for x in src.rglob("*") if x.is_file()):
            arc = (Path(arcroot) / p.relative_to(src)).as_posix() if arcroot else p.relative_to(src).as_posix()
            zi = zipfile.ZipInfo(arc, ZIP_TIME)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, p.read_bytes())
    return zip_path


def _meta(skill: Path) -> tuple[dict, str]:
    fm, body, _ = frontmatter.parse((skill / "SKILL.md").read_text(encoding="utf-8"))
    return fm, body


def _plugin_manifest(skills: list[Path]) -> dict:
    return {
        "name": PRODUCT, "version": __version__, "description": DESCRIPTION,
        "author": {"name": "KnowledgeWala", "url": "https://github.com/dharmsahu-hash"},
        "license": "MIT", "keywords": ["sdlc", "architecture", "java", "spring-boot", "code-review", "knowledgewala"],
    }


def build_generic(skills: list[Path], out: Path) -> list[Path]:
    arts = []
    for s in skills:
        stage = out / "_stage" / s.name
        copy_skill(s, stage)
        arts.append(zip_dir(stage, out / f"{s.name}-{__version__}.zip", s.name))
    shutil.rmtree(out / "_stage")
    return arts


def build_agensi(skills: list[Path], out: Path) -> list[Path]:
    # Agensi consumes the open SKILL.md format; we ship the same canonical folder as a zip.
    # Upload is manual: no public publishing API was found (see marketplace/agensi/README.md).
    return build_generic(skills, out)


def build_claude_code(skills: list[Path], out: Path) -> list[Path]:
    root = out / PRODUCT
    if root.exists():
        shutil.rmtree(root)
    for s in skills:
        copy_skill(s, root / "skills" / s.name)
    (root / ".claude-plugin").mkdir(parents=True)
    (root / ".claude-plugin" / "plugin.json").write_text(json.dumps(_plugin_manifest(skills), indent=2) + "\n", encoding="utf-8")
    for extra in ("LICENSE", "NOTICE.md"):
        src = Path(__file__).resolve().parents[2] / extra
        if src.is_file():
            shutil.copyfile(src, root / extra)
    arts = [zip_dir(root, out / f"{PRODUCT}-claude-code-{__version__}.zip", PRODUCT)]
    # Per-skill zips laid out for ~/.claude/skills/<name>/ or .claude/skills/<name>/
    arts += build_generic(skills, out / "per-skill")
    return arts


def _cursor_rule(skill: Path) -> str:
    fm, body = _meta(skill)
    name = skill.name
    prefix = f".cursor/skills/{name}/"
    body = re.sub(r"(?<![\w/.\-])((?:references|templates|scripts|assets)/[\w./\-]+)", lambda m: prefix + m.group(1), body)
    desc = fm["description"].replace('"', "'")
    return f'---\ndescription: "{desc}"\nalwaysApply: false\n---\n\n<!-- generated by kw-skills from canonical skill {name} v{fm["metadata"]["version"]}; do not edit -->\n{body.lstrip()}'


def build_cursor(skills: list[Path], out: Path) -> list[Path]:
    root = out / "workspace"
    if root.exists():
        shutil.rmtree(root)
    for s in skills:
        copy_skill(s, root / ".cursor" / "skills" / s.name)  # resources + native-skills layout (support: see COMPATIBILITY.md)
        rule = root / ".cursor" / "rules" / f"{s.name}.mdc"
        rule.parent.mkdir(parents=True, exist_ok=True)
        rule.write_text(_cursor_rule(s), encoding="utf-8")
    return [zip_dir(root, out / f"{PRODUCT}-cursor-{__version__}.zip")]


def build_copilot(skills: list[Path], out: Path) -> list[Path]:
    root = out / "workspace"
    if root.exists():
        shutil.rmtree(root)
    lines = ["# Engineering skills available in this repository", "",
             "Generated by kw-skills. Each skill lives in `.github/skills/<name>/SKILL.md`.", ""]
    for s in skills:
        fm, _ = _meta(s)
        copy_skill(s, root / ".github" / "skills" / s.name)
        lines.append(f"- `{s.name}`: {fm['description'][:200]}")
    (root / ".github").mkdir(parents=True, exist_ok=True)
    (root / ".github" / "copilot-instructions.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [zip_dir(root, out / f"{PRODUCT}-github-copilot-{__version__}.zip")]


BUILDERS = {"generic": build_generic, "agensi": build_agensi, "claude-code": build_claude_code,
            "cursor": build_cursor, "github-copilot": build_copilot}


def package(root: Path, platforms: list[str], only: list[str] | None = None, dist: Path | None = None) -> dict:
    skills = discover_skills(root)
    if only:
        missing = set(only) - {s.name for s in skills}
        if missing:
            raise ValueError(f"unknown skill(s): {', '.join(sorted(missing))}")
        skills = [s for s in skills if s.name in only]
    dist = dist or root / "dist"
    result: dict[str, list[dict]] = {}
    for plat in platforms:
        if plat not in BUILDERS:
            raise ValueError(f"unknown platform '{plat}' (choose from {', '.join(PLATFORMS)})")
        out = dist / plat
        out.mkdir(parents=True, exist_ok=True)
        arts = BUILDERS[plat](skills, out)
        result[plat] = [{"file": str(a.relative_to(dist)), "sha256": sha256(a), "bytes": a.stat().st_size} for a in arts]
    return result
